#!/usr/bin/env python3
"""Turns the OpenAPI document of the running backend into docs/api-reference.md.

Usage (backend running, for example `SPRING_PROFILES_ACTIVE=local ./gradlew bootRun`):

    curl -s http://localhost:8080/v3/api-docs -o openapi.json
    python docs/tools/openapi_to_markdown.py openapi.json docs/api-reference.md

Only the standard library is used. The OpenAPI document is generated from the controllers, so the tables below always
describe the code that produced it. What the document does not contain (who may call an endpoint, error codes, business
rules) is written by hand in docs/api-reference-notes.md, which is appended to the output.
"""
import json
import sys
from collections import OrderedDict
from pathlib import Path

# Endpoints that need no token. Keep equal to SecurityConfig.apiSecurity (a test there covers the real rules).
PUBLIC = {
    ("POST", "/api/auth/register"), ("POST", "/api/auth/login"),
    ("GET", "/api/spots"), ("GET", "/api/spots/{id}"), ("GET", "/api/spots/{spotId}/reviews"),
    ("GET", "/api/spots/{spotId}/availability-rules"), ("GET", "/api/spots/events"),
    ("POST", "/api/reservations/quote"),
}
METHOD_ORDER = ["get", "post", "put", "patch", "delete"]


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def type_of(schema: dict) -> str:
    """Short readable type of a JSON schema fragment."""
    if not schema:
        return "any"
    if "$ref" in schema:
        return ref_name(schema["$ref"])
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    t = schema.get("type", "object")
    if t == "array":
        return f"array of {type_of(schema.get('items', {}))}"
    fmt = schema.get("format")
    return f"{t} ({fmt})" if fmt else t


def constraints(schema: dict) -> str:
    out = []
    for key, label in (("minLength", "min length"), ("maxLength", "max length"), ("minimum", "min"), ("maximum", "max"),
                       ("pattern", "pattern")):
        if key in schema:
            out.append(f"{label} {schema[key]}")
    if "default" in schema:
        out.append(f"default {schema['default']}")
    return ", ".join(out)


def schema_table(name: str, schema: dict) -> list:
    lines = [f"### {name}", ""]
    props = schema.get("properties", {})
    if not props:
        lines += [f"Type: {type_of(schema)}", ""]
        return lines
    required = set(schema.get("required", []))
    lines += ["| Field | Type | Required | Notes |", "| --- | --- | --- | --- |"]
    for field, spec in props.items():
        lines.append(f"| `{field}` | {type_of(spec)} | {'yes' if field in required else 'no'} | {constraints(spec)} |")
    lines.append("")
    return lines


def response_summary(responses: dict) -> str:
    parts = []
    for code, spec in responses.items():
        content = spec.get("content", {})
        schema = next(iter(content.values()), {}).get("schema") if content else None
        parts.append(f"`{code}`" + (f" {type_of(schema)}" if schema else ""))
    return ", ".join(parts)


def main(src: str, dst: str) -> None:
    doc = json.loads(Path(src).read_text(encoding="utf-8"))
    info = doc["info"]
    schemas = doc.get("components", {}).get("schemas", {})
    groups = OrderedDict()
    for path, item in doc["paths"].items():
        for method in METHOD_ORDER:
            op = item.get(method)
            if op:
                groups.setdefault(op.get("tags", ["other"])[0], []).append((method.upper(), path, op))

    out = [
        "# REST API reference", "",
        "<!-- Generated by docs/tools/openapi_to_markdown.py from /v3/api-docs. Do not edit by hand; edit the controllers "
        "or docs/api-reference-notes.md. -->", "",
        f"{info.get('title', '')} version {info.get('version', '')}. {info.get('description', '')}", "",
        f"{sum(len(v) for v in groups.values())} operations in {len(groups)} controllers. "
        "Every operation needs `Authorization: Bearer <JWT>` unless the table says *public*. "
        "Errors, roles and business rules are in [Notes](#notes-on-the-api).", "",
        "## Contents", "",
    ]
    for tag, ops in groups.items():
        out.append(f"- [{tag}](#{tag}) ({len(ops)})")
    out += ["- [Schemas](#schemas)", "- [Notes on the API](#notes-on-the-api)", ""]

    for tag, ops in groups.items():
        out += [f"## {tag}", "", "| Method | Path | Access | Request | Response |", "| --- | --- | --- | --- | --- |"]
        for method, path, op in ops:
            access = "public" if (method, path) in PUBLIC else "token"
            body = op.get("requestBody", {}).get("content", {})
            request = ""
            if body:
                media, spec = next(iter(body.items()))
                request = f"`{media}` {type_of(spec.get('schema', {}))}"
            out.append(f"| {method} | `{path}` | {access} | {request} | {response_summary(op.get('responses', {}))} |")
        out.append("")
        for method, path, op in ops:
            params = op.get("parameters", [])
            if not params:
                continue
            out += [f"**{method} `{path}` parameters**", "", "| Name | In | Type | Required | Notes |", "| --- | --- | --- | --- | --- |"]
            for p in params:
                out.append(f"| `{p['name']}` | {p['in']} | {type_of(p.get('schema', {}))} | "
                           f"{'yes' if p.get('required') else 'no'} | {constraints(p.get('schema', {}))} |")
            out.append("")

    out += ["## Schemas", ""]
    for name in sorted(schemas):
        out += schema_table(name, schemas[name])

    notes = Path(__file__).resolve().parent.parent / "api-reference-notes.md"
    out += ["## Notes on the API", ""]
    out.append(notes.read_text(encoding="utf-8").rstrip() + "\n" if notes.exists() else "_No notes file._\n")
    Path(dst).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {dst}: {sum(len(v) for v in groups.values())} operations, {len(schemas)} schemas")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
